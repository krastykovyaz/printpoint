const rtlLanguages = new Set(["ar", "ur"]);
const STORAGE_KEY = "pp-lang";

function detectDefaultLanguage() {
  try {
    const urlLang = new URLSearchParams(window.location.search).get("lang");
    if (urlLang && Object.hasOwn(translations, urlLang)) return urlLang;
  } catch (error) {
    // URL parsing unavailable — fall through to other detection methods.
  }
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && Object.hasOwn(translations, saved)) return saved;
  } catch (error) {
    // localStorage unavailable (private mode, etc.) — fall through to detection.
  }
  const browserLangs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || "en"];
  for (const lang of browserLangs) {
    const code = lang.slice(0, 2).toLowerCase();
    if (Object.hasOwn(translations, code)) return code;
  }
  return "en";
}

let currentLang = detectDefaultLanguage();

// The server publishes the current minimum order in the page head, so it can be changed without a new build.
const minOrder = Number(document.querySelector('meta[name="min-copies"]')?.content) || 4;

// Price rules in cents, published by the server (see PRICE_RULES in app.js).
const priceRules = (() => {
  try {
    return JSON.parse(document.querySelector('meta[name="price-rules"]')?.content || "null");
  } catch {
    return null;
  }
})();
// One price for every page plus a minimum total (the pilot price) gets its own, simpler note.
if (priceRules && priceRules.page === priceRules.bulk && priceRules.min > 0) {
  document.querySelector('[data-i18n="priceRatesNote"]')?.setAttribute("data-i18n", "priceRatesNoteFlat");
}

function t(key) {
  const text = (translations[currentLang] && translations[currentLang][key]) || translations.en[key] || key;
  return text
    .replace("{min}", minOrder)
    .replace("{page}", priceRules ? (priceRules.page / 100).toFixed(2) : "")
    .replace("{minTotal}", priceRules ? (priceRules.min / 100).toFixed(2) : "");
}

function applyLanguage(lang) {
  currentLang = Object.hasOwn(translations, lang) ? lang : "en";
  document.documentElement.lang = currentLang;
  document.documentElement.dir = rtlLanguages.has(currentLang) ? "rtl" : "ltr";
  document.title = t("pageTitle");

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    el.setAttribute("alt", t(el.dataset.i18nAlt));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });

  const select = document.querySelector("#language-select");
  if (select) select.value = currentLang;

  try {
    localStorage.setItem(STORAGE_KEY, currentLang);
  } catch (error) {
    // Ignore write failures — language choice just won't persist across visits.
  }

  try {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", currentLang);
    window.history.replaceState(null, "", url);
  } catch (error) {
    // URL update is best-effort — sharing will just fall back to the default language.
  }
}

window.i18n = {
  t,
  applyLanguage,
  get currentLang() {
    return currentLang;
  }
};

document.addEventListener("DOMContentLoaded", () => {
  applyLanguage(currentLang);
  const select = document.querySelector("#language-select");
  if (select) {
    select.addEventListener("change", (event) => applyLanguage(event.target.value));
  }
});
